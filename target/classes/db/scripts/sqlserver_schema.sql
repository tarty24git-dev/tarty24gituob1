-- Database Engine: Microsoft SQL Server 2019/2022
-- =========================================================

CREATE TABLE USERS (
    ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    PHONE_NUMBER VARCHAR(20),
    FULL_NAME VARCHAR(100) NOT NULL,
    ROLE VARCHAR(20) NOT NULL DEFAULT 'USER',
    LOCKED BIT NOT NULL DEFAULT 0,
    ENABLED BIT NOT NULL DEFAULT 1,
    PASSWORD_EXPIRED BIT NOT NULL DEFAULT 0,
    PASSWORD_CHANGED_AT DATETIME DEFAULT GETDATE(),
    VERIFIED BIT NOT NULL DEFAULT 1,
    CREATED_AT DATETIME DEFAULT GETDATE(),
    UPDATED_AT DATETIME DEFAULT GETDATE()
);

CREATE TABLE REPORT_CONFIGS (
    ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    REPORT_NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(255),
    TARGET_TABLE VARCHAR(100) NOT NULL,
    SELECTED_FIELDS VARCHAR(1000) NOT NULL,
    FILTER_CONDITIONS VARCHAR(1000),
    SORT_BY VARCHAR(100),
    CREATED_BY VARCHAR(50) NOT NULL,
    CRON_EXPRESSION VARCHAR(50),
    ACTIVE BIT NOT NULL DEFAULT 1,
    CREATED_AT DATETIME DEFAULT GETDATE()
);

CREATE TABLE COMPARISON_LOGS (
    ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    FILE1_NAME VARCHAR(255) NOT NULL,
    FILE2_NAME VARCHAR(255) NOT NULL,
    KEY_COLUMNS VARCHAR(255) NOT NULL,
    TOTAL_FILE1_ROWS INT NOT NULL,
    TOTAL_FILE2_ROWS INT NOT NULL,
    MATCHED_ROWS INT NOT NULL,
    UNMATCHED_FILE1_ROWS INT NOT NULL,
    UNMATCHED_FILE2_ROWS INT NOT NULL,
    EXECUTED_BY VARCHAR(50) NOT NULL,
    CREATED_AT DATETIME DEFAULT GETDATE()
);

CREATE TABLE AUDIT_LOGS (
    ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL,
    ACTION VARCHAR(100) NOT NULL,
    DETAILS VARCHAR(1000),
    IP_ADDRESS VARCHAR(45),
    CREATED_AT DATETIME DEFAULT GETDATE()
);

CREATE INDEX IDX_MS_USERS_USERNAME ON USERS(USERNAME);
