-- =========================================================
-- PostgreSQL DDL Script for Data Match & Reporting Application
-- Database Engine: PostgreSQL 14+
-- =========================================================

CREATE TABLE USERS (
    ID BIGSERIAL PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    PHONE_NUMBER VARCHAR(20),
    FULL_NAME VARCHAR(100) NOT NULL,
    ROLE VARCHAR(20) NOT NULL DEFAULT 'USER',
    LOCKED BOOLEAN NOT NULL DEFAULT FALSE,
    ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
    PASSWORD_EXPIRED BOOLEAN NOT NULL DEFAULT FALSE,
    PASSWORD_CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    VERIFIED BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE REPORT_CONFIGS (
    ID BIGSERIAL PRIMARY KEY,
    REPORT_NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(255),
    TARGET_TABLE VARCHAR(100) NOT NULL,
    SELECTED_FIELDS VARCHAR(1000) NOT NULL,
    FILTER_CONDITIONS VARCHAR(1000),
    SORT_BY VARCHAR(100),
    CREATED_BY VARCHAR(50) NOT NULL,
    CRON_EXPRESSION VARCHAR(50),
    ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE COMPARISON_LOGS (
    ID BIGSERIAL PRIMARY KEY,
    FILE1_NAME VARCHAR(255) NOT NULL,
    FILE2_NAME VARCHAR(255) NOT NULL,
    KEY_COLUMNS VARCHAR(255) NOT NULL,
    TOTAL_FILE1_ROWS INT NOT NULL,
    TOTAL_FILE2_ROWS INT NOT NULL,
    MATCHED_ROWS INT NOT NULL,
    UNMATCHED_FILE1_ROWS INT NOT NULL,
    UNMATCHED_FILE2_ROWS INT NOT NULL,
    EXECUTED_BY VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE AUDIT_LOGS (
    ID BIGSERIAL PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL,
    ACTION VARCHAR(100) NOT NULL,
    DETAILS VARCHAR(1000),
    IP_ADDRESS VARCHAR(45),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_PG_USERS_USERNAME ON USERS(USERNAME);
