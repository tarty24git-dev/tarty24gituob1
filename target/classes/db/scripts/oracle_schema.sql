-- Database Engine: Oracle Database 19c/21c
-- =========================================================

CREATE TABLE USERS (
    ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    PHONE_NUMBER VARCHAR2(20),
    FULL_NAME VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    LOCKED NUMBER(1) DEFAULT 0 NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    PASSWORD_EXPIRED NUMBER(1) DEFAULT 0 NOT NULL,
    PASSWORD_CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    VERIFIED NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE REPORT_CONFIGS (
    ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    REPORT_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(255),
    TARGET_TABLE VARCHAR2(100) NOT NULL,
    SELECTED_FIELDS VARCHAR2(1000) NOT NULL,
    FILTER_CONDITIONS VARCHAR2(1000),
    SORT_BY VARCHAR2(100),
    CREATED_BY VARCHAR2(50) NOT NULL,
    CRON_EXPRESSION VARCHAR2(50),
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE COMPARISON_LOGS (
    ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    FILE1_NAME VARCHAR2(255) NOT NULL,
    FILE2_NAME VARCHAR2(255) NOT NULL,
    KEY_COLUMNS VARCHAR2(255) NOT NULL,
    TOTAL_FILE1_ROWS NUMBER(10) NOT NULL,
    TOTAL_FILE2_ROWS NUMBER(10) NOT NULL,
    MATCHED_ROWS NUMBER(10) NOT NULL,
    UNMATCHED_FILE1_ROWS NUMBER(10) NOT NULL,
    UNMATCHED_FILE2_ROWS NUMBER(10) NOT NULL,
    EXECUTED_BY VARCHAR2(50) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE AUDIT_LOGS (
    ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL,
    ACTION VARCHAR2(100) NOT NULL,
    DETAILS VARCHAR2(1000),
    IP_ADDRESS VARCHAR2(45),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_ORA_USERS_USERNAME ON USERS(USERNAME);
