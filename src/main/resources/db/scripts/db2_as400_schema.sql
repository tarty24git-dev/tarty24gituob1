CREATE TABLE USERS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    USERNAME VARCHAR(50) NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL,
    PHONE_NUMBER VARCHAR(20),
    FULL_NAME VARCHAR(100) NOT NULL,
    ROLE VARCHAR(20) DEFAULT 'USER' NOT NULL,
    LOCKED SMALLINT DEFAULT 0 NOT NULL,
    ENABLED SMALLINT DEFAULT 1 NOT NULL,
    PASSWORD_EXPIRED SMALLINT DEFAULT 0 NOT NULL,
    PASSWORD_CHANGED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    VERIFIED SMALLINT DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (ID),
    CONSTRAINT UQ_AS400_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_AS400_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE REPORT_CONFIGS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    REPORT_NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(255),
    TARGET_TABLE VARCHAR(100) NOT NULL,
    SELECTED_FIELDS VARCHAR(1000) NOT NULL,
    FILTER_CONDITIONS VARCHAR(1000),
    SORT_BY VARCHAR(100),
    CREATED_BY VARCHAR(50) NOT NULL,
    CRON_EXPRESSION VARCHAR(50),
    ACTIVE SMALLINT DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (ID)
);

CREATE TABLE COMPARISON_LOGS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    FILE1_NAME VARCHAR(255) NOT NULL,
    FILE2_NAME VARCHAR(255) NOT NULL,
    KEY_COLUMNS VARCHAR(255) NOT NULL,
    TOTAL_FILE1_ROWS INT NOT NULL,
    TOTAL_FILE2_ROWS INT NOT NULL,
    MATCHED_ROWS INT NOT NULL,
    UNMATCHED_FILE1_ROWS INT NOT NULL,
    UNMATCHED_FILE2_ROWS INT NOT NULL,
    EXECUTED_BY VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (ID)
);

CREATE TABLE AUDIT_LOGS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    USERNAME VARCHAR(50) NOT NULL,
    ACTION VARCHAR(100) NOT NULL,
    DETAILS VARCHAR(1000),
    IP_ADDRESS VARCHAR(45),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (ID)
);

CREATE INDEX IDX_AS400_USERS_USER ON USERS(USERNAME);
