-- =========================================================
-- DB2 DDL Script for Data Match & Reporting Application
-- Database Engine: IBM DB2
-- Target Schema: DATAMATCH
-- =========================================================

-- Create USERS table
CREATE TABLE USERS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    USERNAME VARCHAR(50) NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL,
    PHONE_NUMBER VARCHAR(20),
    FULL_NAME VARCHAR(100) NOT NULL,
    ROLE VARCHAR(20) NOT NULL DEFAULT 'USER',
    LOCKED SMALLINT NOT NULL DEFAULT 0,
    ENABLED SMALLINT NOT NULL DEFAULT 1,
    PASSWORD_EXPIRED SMALLINT NOT NULL DEFAULT 0,
    PASSWORD_CHANGED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    VERIFIED SMALLINT NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (ID),
    CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
);

-- Create REPORT_CONFIGS table
CREATE TABLE REPORT_CONFIGS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    REPORT_NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(255),
    TARGET_TABLE VARCHAR(100) NOT NULL,
    SELECTED_FIELDS VARCHAR(1000) NOT NULL,
    FILTER_CONDITIONS VARCHAR(1000),
    SORT_BY VARCHAR(100),
    CREATED_BY VARCHAR(50) NOT NULL,
    CRON_EXPRESSION VARCHAR(50),
    ACTIVE SMALLINT NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (ID)
);

-- Create COMPARISON_LOGS table
CREATE TABLE COMPARISON_LOGS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    FILE1_NAME VARCHAR(255) NOT NULL,
    FILE2_NAME VARCHAR(255) NOT NULL,
    KEY_COLUMNS VARCHAR(255) NOT NULL,
    TOTAL_FILE1_ROWS INT NOT NULL,
    TOTAL_FILE2_ROWS INT NOT NULL,
    MATCHED_ROWS INT NOT NULL,
    UNMATCHED_FILE1_ROWS INT NOT NULL,
    UNMATCHED_FILE2_ROWS INT NOT NULL,
    EXECUTED_BY VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (ID)
);

-- Create AUDIT_LOGS table
CREATE TABLE AUDIT_LOGS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    USERNAME VARCHAR(50) NOT NULL,
    ACTION VARCHAR(100) NOT NULL,
    DETAILS VARCHAR(1000),
    IP_ADDRESS VARCHAR(45),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (ID)
);

-- Create INDEXES for faster query execution
CREATE INDEX IDX_USERS_USERNAME ON USERS(USERNAME);
CREATE INDEX IDX_AUDIT_LOGS_USER ON AUDIT_LOGS(USERNAME);
